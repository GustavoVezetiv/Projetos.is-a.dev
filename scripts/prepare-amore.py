"""Prepare reviewed media locally. Requires Pillow and ffmpeg/ffprobe on PATH.

Originals are never overwritten; only assets/amore contains generated output.
No chat export, contacts or original metadata are copied into the site.
"""
import io
import json
import subprocess
from pathlib import Path
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'TresAnos' / 'Amore'
OUTPUT = ROOT / 'TresAnos' / 'assets' / 'amore'
OUTPUT.mkdir(parents=True, exist_ok=True)

# All 19 new photographs plus six earlier photographs and the 15 reviewed clips.
PHOTOS = [
    '20250614_224016.jpg', '20250706_021950.jpg', '20250914_024108.jpg',
    '20250921_005034.jpg', '20250928_205200.jpg', '20250928_205215.jpg',
    '20251031_183619.jpg', '20251231_222202.heic', '20251231_222324.heic',
    '20260216_205145.heic', '20260315_180214.heic', '20260411_153023.heic',
    '20260712_131441.heic', '20260712_131449.jpg',
    'file_000000002428720e9f5f9704180f3339.png', 'IMG_20260308_203827_019.webp',
    'IMG-20261004-WA0062.jpg', 'motion_photo_3360288516225348448.jpg',
    'motion_photo_4245745456141610112.jpg',
    'IMG_20231020_230101_960.webp', 'IMG_20240213_211925_641.webp',
    '20241102_170313.jpg', '20250419_121703.jpg',
    'IMG_20250504_144844_971(1).jpg', '20250608_001615.jpg',
]


def run(arguments):
    return subprocess.run(arguments, capture_output=True, check=True).stdout


def read_photo(path):
    if path.suffix.lower() == '.heic':
        frame = run(['ffmpeg', '-v', 'error', '-i', str(path), '-frames:v', '1',
                     '-f', 'image2pipe', '-vcodec', 'png', '-threads', '1', 'pipe:1'])
        image = Image.open(io.BytesIO(frame))
    else:
        image = Image.open(path)
    return ImageOps.exif_transpose(image).convert('RGB')


def save_photo(image, path, size):
    # Build a fresh pixel buffer to discard EXIF, location and source metadata.
    resized = ImageOps.contain(image, (size, size), Image.Resampling.LANCZOS)
    clean = Image.new('RGB', resized.size)
    clean.paste(resized)
    clean.save(path, 'WEBP', quality=84 if size > 1000 else 78, method=6)


manifest = {}
for filename in PHOTOS:
    source = SOURCE / filename
    identifier = source.stem.replace('(', '-').replace(')', '')
    image = read_photo(source)
    full = OUTPUT / f'{identifier}.webp'
    thumb = OUTPUT / f'{identifier}-thumb.webp'
    save_photo(image, full, 1600)
    save_photo(image, thumb, 640)
    manifest[identifier] = {
        'type': 'image', 'file': f'./assets/amore/{full.name}',
        'thumb': f'./assets/amore/{thumb.name}',
        'width': image.width, 'height': image.height,
    }
    print(f'Photo: {filename}', flush=True)

for source in sorted(SOURCE.glob('*.mp4')):
    identifier = source.stem
    full = OUTPUT / f'{identifier}.mp4'
    poster = OUTPUT / f'{identifier}-poster.webp'
    metadata = json.loads(run(['ffprobe', '-v', 'error', '-show_entries',
                              'format=duration', '-of', 'json', str(source)]))
    duration = float(metadata['format']['duration'])
    # Keep the whole clip and its audio, just encode a browser-compatible copy.
    # ffmpeg autorotation is applied before scaling and metadata is discarded.
    run(['ffmpeg', '-v', 'error', '-y', '-i', str(source), '-map', '0:v:0',
         '-map', '0:a?', '-vf', 'scale=720:1280:force_original_aspect_ratio=decrease:force_divisible_by=2,setsar=1',
         '-c:v', 'libx264', '-preset', 'fast', '-crf', '24', '-pix_fmt', 'yuv420p',
         '-c:a', 'aac', '-b:a', '128k', '-map_metadata', '-1', '-movflags', '+faststart', str(full)])
    frame = run(['ffmpeg', '-v', 'error', '-ss', str(round(duration * .4, 3)),
                 '-i', str(full), '-frames:v', '1', '-f', 'image2pipe',
                 '-vcodec', 'png', '-threads', '1', 'pipe:1'])
    image = Image.open(io.BytesIO(frame)).convert('RGB')
    save_photo(image, poster, 640)
    manifest[identifier] = {
        'type': 'video', 'file': f'./assets/amore/{full.name}',
        'poster': f'./assets/amore/{poster.name}',
        'thumb': f'./assets/amore/{poster.name}',
        'width': image.width, 'height': image.height, 'duration': round(duration, 2),
    }
    print(f'Video: {source.name} / {duration:.1f}s', flush=True)

(OUTPUT / 'manifest.js').write_text(
    '// Generated by scripts/prepare-amore.py. Reviewed media only.\n'
    'export const preparedMedia = ' + json.dumps(manifest, ensure_ascii=False, indent=2) + ';\n',
    encoding='utf-8',
)
print(json.dumps({'photos': len(PHOTOS), 'videos': len(manifest) - len(PHOTOS),
                  'outputMB': round(sum(path.stat().st_size for path in OUTPUT.iterdir()) / 1048576, 2)}))
